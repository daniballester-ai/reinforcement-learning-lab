        "import os, sys, subprocess, time\n"
        "COMBOS = [('pong', 'dqn'), ('pong', 'ddqn'), ('spaceinvaders', 'dqn'), ('spaceinvaders', 'ddqn')]\n"
        "\n"
        "def build_cmd(jogo, algo, runs_root, extra):\n"
        "    return [sys.executable, '-m', 'rl_lab.run', '--env', jogo, '--algo', algo, '--seed', '0',\n"
        "            '--out', runs_root, '--resume'] + extra.split()\n"
        "\n"
        "def last_step(runs_root, jogo, algo):\n"
        "    f = f'{runs_root}/{jogo}/{algo}/seed0/episodes.csv'\n"
        "    if not os.path.exists(f):\n"
        "        return 0\n"
        "    lines = [l for l in open(f).read().splitlines()[1:] if l.strip()]\n"
        "    return int(float(lines[-1].split(',')[0])) if lines else 0\n"
